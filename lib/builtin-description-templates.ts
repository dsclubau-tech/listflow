export function isExactBuiltinDescriptionTemplateContent(content: string): boolean {
  return (
    content.includes('<meta content="IE=edge" http-equiv="X-UA-Compatible" />') &&
    content.includes('<link href="https://maxcdn.bootstrapcdn.com/bootstrap/3.3.7/css/bootstrap.min.css" rel="stylesheet" />') &&
    content.includes('<link href="https://images.autods.com/template_static/SimpleBlueStyle.css" rel="stylesheet" type="text/css" />') &&
    content.includes('<div id="wrapper">')
  );
}

export function normalizeBuiltinDescriptionTemplate<T extends { id: string; content: string }>(template: T): T {
  if (
    template.id === RK_ECOM_30_DAY_FREE_RETURN_TEMPLATE_ID &&
    !isExactBuiltinDescriptionTemplateContent(template.content)
  ) {
    return {
      ...template,
      content: RK_ECOM_30_DAY_FREE_RETURN_TEMPLATE_CONTENT,
    };
  }

  return template;
}
